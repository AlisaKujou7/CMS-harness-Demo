import { z } from 'zod';
import {
  contentListQuery,
  createContentRequest,
  rejectContentRequest,
  scheduleContentRequest,
  updateContentRequest,
} from '../../modules/content/adapters/in/http/content.controller.js';
import { pageQuery } from '../../shared/adapters/http/pagination.js';
import * as c from './contract-schemas.js';
import type { ApiRoute } from './route-types.js';

const CONTENT = '/api/admin/content';
const MODERATORS = 'Admin or Editor';
const contentResult = c.single(c.content);
const any = { tag: 'Content', auth: 'bearer' } as const;
const moderator = { ...any, roles: MODERATORS } as const;
const one = `${CONTENT}/{id}`;

export const CONTENT_ROUTES: readonly ApiRoute[] = [
  {
    ...any,
    method: 'get',
    path: CONTENT,
    id: 'listContent',
    summary: 'List content. Authors see only their own',
    query: contentListQuery,
    status: 200,
    response: c.listOf(c.contentListItem),
  },
  {
    ...any,
    method: 'post',
    path: CONTENT,
    id: 'createContent',
    summary: 'Create a draft',
    body: createContentRequest,
    status: 201,
    response: contentResult,
  },
  {
    ...any,
    method: 'get',
    path: `${CONTENT}/stats`,
    id: 'getContentStats',
    summary: 'Count content by status',
    status: 200,
    response: c.single(c.contentStats),
  },
  {
    ...any,
    method: 'get',
    path: `${CONTENT}/categories`,
    id: 'listContentCategories',
    summary: 'List the predefined categories',
    status: 200,
    response: c.allOf(z.string()),
  },
  {
    ...any,
    method: 'get',
    path: one,
    id: 'getContent',
    summary: 'Get content',
    status: 200,
    response: contentResult,
  },
  {
    ...any,
    method: 'patch',
    path: one,
    id: 'updateContent',
    summary: 'Save changes. Refused if someone else saved first',
    body: updateContentRequest,
    status: 200,
    response: contentResult,
  },
  {
    ...moderator,
    method: 'delete',
    path: one,
    id: 'deleteContent',
    summary: 'Delete content, which is purged after 30 days',
    status: 204,
  },
  {
    ...any,
    method: 'post',
    path: `${one}/submit`,
    id: 'submitContent',
    summary: 'Submit for review',
    status: 200,
    response: contentResult,
  },
  {
    ...moderator,
    method: 'post',
    path: `${one}/publish`,
    id: 'publishContent',
    summary: 'Publish',
    status: 200,
    response: contentResult,
  },
  {
    ...moderator,
    method: 'post',
    path: `${one}/reject`,
    id: 'rejectContent',
    summary: 'Send back to draft with a note',
    body: rejectContentRequest,
    status: 200,
    response: contentResult,
  },
  {
    ...moderator,
    method: 'post',
    path: `${one}/unpublish`,
    id: 'unpublishContent',
    summary: 'Unpublish',
    status: 200,
    response: contentResult,
  },
  {
    ...moderator,
    method: 'post',
    path: `${one}/archive`,
    id: 'archiveContent',
    summary: 'Archive',
    status: 200,
    response: contentResult,
  },
  {
    ...moderator,
    method: 'post',
    path: `${one}/schedule`,
    id: 'scheduleContent',
    summary: 'Schedule publishing, or cancel with null',
    body: scheduleContentRequest,
    status: 200,
    response: contentResult,
  },
  {
    ...any,
    method: 'get',
    path: `${one}/versions`,
    id: 'listContentVersions',
    summary: 'List versions',
    query: pageQuery,
    status: 200,
    response: c.listOf(c.contentVersion),
  },
  {
    ...any,
    method: 'get',
    path: `${one}/versions/{version}`,
    id: 'getContentVersion',
    summary: 'Get one version',
    status: 200,
    response: c.single(c.contentVersionDetail),
  },
  {
    ...any,
    method: 'post',
    path: `${one}/revert/{version}`,
    id: 'revertContent',
    summary: 'Restore a version as a new version',
    status: 200,
    response: contentResult,
  },
];
